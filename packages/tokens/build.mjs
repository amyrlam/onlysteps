// Builds the DTCG token files in ./tokens into:
//   dist/tokens.css   CSS custom properties (light on :root, dark on .dark)
//   dist/tokens.json  flat resolved values for JS/TS
//   ../../apps/ios/OnlySteps/DesignSystem/Tokens.swift  SwiftUI constants
//
// `node build.mjs --check` builds to a temp dir and fails if the committed
// Swift file is out of date, so CI catches token edits that weren't rebuilt.
import { mkdir, readFile, writeFile, mkdtemp } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import StyleDictionary from "style-dictionary";

const here = path.dirname(fileURLToPath(import.meta.url));
const check = process.argv.includes("--check");
const distDir = check ? await mkdtemp(path.join(tmpdir(), "tokens-")) : path.join(here, "dist");
const swiftPath = path.join(here, "../../apps/ios/OnlySteps/DesignSystem/Tokens.swift");

const kebab = (parts) => parts.join("-");
const camel = (parts) =>
  parts
    .join("-")
    .split(/[-.]/)
    .map((p, i) => (i === 0 ? p : p[0].toUpperCase() + p.slice(1)))
    .join("")
    .replace(/^(\d)/, "_$1");

// DTCG 2025.10 color: { colorSpace, components, alpha?, hex? }
function cssColor(v) {
  const a = v.alpha ?? 1;
  const alpha = a === 1 ? "" : ` / ${a}`;
  switch (v.colorSpace) {
    case "oklch":
      return `oklch(${v.components[0]} ${v.components[1]} ${v.components[2]}${alpha})`;
    case "srgb":
      return `rgb(${v.components.map((c) => Math.round(c * 255)).join(" ")}${alpha})`;
    default:
      if (v.hex) return v.hex;
      throw new Error(`Unsupported colorSpace ${v.colorSpace}`);
  }
}

function hexToRgb(hex) {
  const n = parseInt(hex.replace("#", ""), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((c) => +(c / 255).toFixed(4));
}

// DTCG dimension/duration: { value, unit }
const cssDimension = (v) => `${v.value}${v.unit}`;

function cssValue(token) {
  const v = token.$value;
  switch (token.$type) {
    case "color":
      return cssColor(v);
    case "dimension":
    case "duration":
      return cssDimension(v);
    case "fontFamily":
      return (Array.isArray(v) ? v : [v]).map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
    default:
      return String(v);
  }
}

async function resolve(mode) {
  const sd = new StyleDictionary({
    source: [path.join(here, "tokens/primitives.tokens.json"), path.join(here, `tokens/semantic.${mode}.tokens.json`)],
    usesDtcg: true,
    log: { verbosity: "silent" },
    platforms: { raw: {} },
  });
  const dict = await sd.getPlatformTokens("raw");
  return dict.allTokens;
}

const light = await resolve("light");
const dark = await resolve("dark");
const isSemantic = (t) => t.path[0] === "semantic";
// CSS name: semantic tokens drop the group (they mirror shadcn: --primary).
const groupPrefix = { semantic: null, dimension: null, fontFamily: "font", fontWeight: "font-weight" };
// Non-semantic tokens get an `os-` prefix so they don't collide with
// Tailwind's own theme variables; packages/ui maps them into @theme.
const cssName = (t) => {
  const [group, ...rest] = t.path;
  if (group === "semantic") return kebab(rest);
  if (!(group in groupPrefix)) return kebab(["os", ...t.path]);
  return kebab(["os", ...(groupPrefix[group] ? [groupPrefix[group], ...rest] : rest)]);
};

// ---- CSS ----
const block = (sel, tokens) => `${sel} {\n${tokens.map((t) => `  --${cssName(t)}: ${cssValue(t)};`).join("\n")}\n}\n`;
const rootTokens = light.filter((t) => isSemantic(t) || t.path[0] !== "color");
const css =
  "/* Generated by packages/tokens/build.mjs. Do not edit. */\n" +
  block(":root", rootTokens) +
  "\n" +
  block(".dark", dark.filter(isSemantic));

// ---- JSON ----
const json = {
  light: Object.fromEntries(light.map((t) => [t.path.join("."), cssValue(t)])),
  dark: Object.fromEntries(dark.filter(isSemantic).map((t) => [t.path.join("."), cssValue(t)])),
};

// ---- Swift ----
const darkByName = new Map(dark.filter(isSemantic).map((t) => [t.name, t]));
const rgb = (t) => {
  const [r, g, b] = hexToRgb(t.$value.hex);
  return `red: ${r}, green: ${g}, blue: ${b}, alpha: ${t.$value.alpha ?? 1}`;
};
const semanticColors = light
  .filter(isSemantic)
  .map((t) => `    static let ${camel(t.path.slice(1))} = Color.dynamic(light: .init(${rgb(t)}), dark: .init(${rgb(darkByName.get(t.name))}))`);
const dims = (group) =>
  light
    .filter((t) => t.path[0] === "dimension" && t.path[1] === group)
    .map((t) => `    static let ${camel(t.path.slice(2))}: CGFloat = ${t.$value.value}`);
const swift = `// Generated by packages/tokens/build.mjs. Do not edit.
import SwiftUI
import UIKit

enum OSColor {
${semanticColors.join("\n")}
}

enum OSSpace {
${dims("space").join("\n")}
}

enum OSRadius {
${dims("radius").join("\n")}
}

private extension Color {
    struct RGBA { let red, green, blue, alpha: Double }

    static func dynamic(light: RGBA, dark: RGBA) -> Color {
        Color(uiColor: UIColor { traits in
            let c = traits.userInterfaceStyle == .dark ? dark : light
            return UIColor(red: c.red, green: c.green, blue: c.blue, alpha: c.alpha)
        })
    }
}
`;

await mkdir(distDir, { recursive: true });
await writeFile(path.join(distDir, "tokens.css"), css);
await writeFile(path.join(distDir, "tokens.json"), JSON.stringify(json, null, 2) + "\n");

if (check) {
  const committed = await readFile(swiftPath, "utf8").catch(() => "");
  if (committed !== swift) {
    console.error("Tokens.swift is out of date. Run `pnpm tokens` and commit the result.");
    process.exit(1);
  }
  console.log("Tokens build OK and Tokens.swift is up to date.");
} else {
  await mkdir(path.dirname(swiftPath), { recursive: true });
  await writeFile(swiftPath, swift);
  console.log(`Built ${light.length} tokens to dist/ and Tokens.swift`);
}
